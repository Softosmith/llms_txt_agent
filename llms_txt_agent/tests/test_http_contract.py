"""W5 -- the HTTP contract of the five llms routes (QA-16, QA-25, QA-32, QA-33, QA-37).

Everything here is asserted against a real request/response round trip or against
the routing registry, because every defect in this band was invisible in the
Python layer and obvious in ``curl -i``:

* QA-16 (FINDINGS D-F, S6) -- "Cached (Hourly)" and "Cached (Daily)" both sent
  ``Cache-Control: public, max-age=3600`` because the string was hardcoded in the
  controller, and the single cron ran every six hours regardless of the mode.  The
  labels were decoration.
* QA-25 (S3, S12) -- ``/llms.md`` sent no ``Cache-Control`` at all, the item routes
  sent neither ``Cache-Control`` nor ``X-Robots-Tag``, and no route sent ``ETag`` or
  ``Last-Modified``, so a crawler could never do a conditional GET.
* QA-32 (D-AG) -- three modules declare the same three index paths; the registry is
  the only place where a disagreement between those declarations becomes visible.
* QA-33 (D-AH) -- three crons regenerated byte-identical documents back to back.
* QA-37 (S4) -- ``/llms.md`` is a deliberate alias of ``/llms.txt``, so it must be
  identical in body *and* headers except ``Content-Type``.
"""

import hashlib
from datetime import timedelta, timezone
from email.utils import format_datetime

from odoo import fields, http as odoo_http
from odoo.tests import HttpCase, TransactionCase, tagged
from odoo.tools import config


def _http_utc(value):
    """An Odoo naive-UTC datetime as an HTTP-date, written *here*.

    Deliberately not imported from ``models/llms_http.py``: the test then states
    the expectation independently of the code that produces the header, so a
    change to the shared helper cannot quietly move the goalposts.
    """
    return format_datetime(value.replace(tzinfo=timezone.utc), usegmt=True)


CACHE_CONTROL = {
    'realtime': 'no-cache, must-revalidate',
    'hourly': 'public, max-age=3600',
    'daily': 'public, max-age=86400',
}
INDEX_PATHS = ('/llms.txt', '/llms-full.txt', '/llms.md')

# The rule *patterns* of the two per-page routes, exactly as the registry holds
# them: one addressable by the page's own URL (``/about.md``) and the legacy
# id-based one (``/llms/page/7.md``).  ``test_listing_claims.py`` and the
# routing-key checks below both work on patterns, because the shape of a route
# is a definition-site fact while a concrete URL is only one instance of it.
ITEM_RULES = ('/<path:page_path>.md', '/llms/page/<int:page_id>.md')


@tagged('post_install', '-at_install')
class TestLlmsHttpContract(HttpCase):
    """Header contract, asserted on live 200 responses."""

    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        cls.website = cls.env['website'].search([], order='id', limit=1)
        cls.website.write({
            'llm_enabled': True,
            'llm_site_title': 'Contract Test Company',
            'llm_site_summary': 'Summary line for the header contract tests.',
            'llm_include_pages': True,
            'llm_cache_ttl': 'hourly',
        })
        cls.view = cls.env['ir.ui.view'].create({
            'name': 'Contract Test Page View',
            'type': 'qweb',
            'arch': '<t t-name="test.contract.page"><div><h1>Contract Page</h1>'
                    '<p>Body copy for the contract test page.</p></div></t>',
            'key': 'test.contract.page',
        })
        cls.page = cls.env['website.page'].create({
            'url': '/contract-test-page',
            'view_id': cls.view.id,
            'website_id': cls.website.id,
            'is_published': True,
            'name': 'Contract Test Page',
        })
        cls.item_path = '/llms/page/%d.md' % cls.page.id
        # The mirrored route resolves a page by its own URL, so the test page's
        # URL is the test URL: ``/contract-test-page.md`` -> ``/contract-test-page``.
        cls.mirror_path = '%s.md' % cls.page.url
        cls.all_paths = INDEX_PATHS + (cls.item_path, cls.mirror_path)

    def setUp(self):
        super().setUp()
        self.website._invalidate_llms_cache()

    # -- helpers ---------------------------------------------------------

    def _set_ttl(self, ttl):
        """Switch generation mode; writes invalidate, so no stale cache leaks in."""
        self.website.llm_cache_ttl = ttl
        self.website._invalidate_llms_cache()

    def _paths(self):
        return self.all_paths

    # -- QA-16: the mode must decide the header --------------------------

    def test_cache_control_matches_generation_mode(self):
        """One documented value per mode, on every route, in every mode."""
        for ttl, expected in CACHE_CONTROL.items():
            self._set_ttl(ttl)
            for path in self._paths():
                r = self.url_open(path)
                self.assertEqual(r.status_code, 200, '%s in %s mode' % (path, ttl))
                self.assertEqual(
                    r.headers.get('Cache-Control'), expected,
                    '%s in %r mode must send %r, sent %r (QA-16)'
                    % (path, ttl, expected, r.headers.get('Cache-Control')))

    def test_hourly_and_daily_are_not_the_same_response(self):
        """The two cached modes must differ, or the labels stay decoration.

        Guards against a "fix" that returns the same string for both branches.
        """
        self._set_ttl('hourly')
        hourly = self.url_open('/llms.txt').headers.get('Cache-Control')
        self._set_ttl('daily')
        daily = self.url_open('/llms.txt').headers.get('Cache-Control')
        self.assertNotEqual(hourly, daily, 'hourly and daily sent one Cache-Control (QA-16)')

    # -- QA-25: nothing may be missing ----------------------------------

    def test_item_routes_carry_robots_and_cache_headers(self):
        """QA-25: the per-page route used to send neither header."""
        r = self.url_open(self.item_path)
        self.assertEqual(r.status_code, 200)
        self.assertEqual(r.headers.get('X-Robots-Tag'), 'all')
        self.assertEqual(r.headers.get('Cache-Control'), CACHE_CONTROL['hourly'])

    def test_llms_md_sends_cache_control(self):
        """QA-25 / S3: /llms.md was the one index route with no Cache-Control."""
        r = self.url_open('/llms.md')
        self.assertEqual(r.status_code, 200)
        self.assertEqual(r.headers.get('Cache-Control'), CACHE_CONTROL['hourly'])

    def test_every_route_offers_an_etag_and_last_modified(self):
        """QA-25: no validator header existed anywhere, so no conditional GET was
        possible -- a crawler polling hourly paid for the full body every time."""
        for path in self._paths():
            r = self.url_open(path)
            self.assertEqual(r.status_code, 200, path)
            etag = r.headers.get('ETag')
            self.assertTrue(etag, '%s has no ETag (QA-25)' % path)
            self.assertTrue(etag.startswith('"') and etag.endswith('"'),
                            '%s sent a weak or unquoted ETag: %r' % (path, etag))
            self.assertNotEqual('W/', etag[:2], '%s is weakly validated' % path)
            last_modified = r.headers.get('Last-Modified')
            self.assertTrue(last_modified, '%s has no Last-Modified (QA-25)' % path)
            # must parse as an HTTP-date, i.e. GMT with no numeric offset
            self.assertIn('GMT', last_modified)

    def test_item_route_last_modified_follows_the_cache_rebuild(self):
        """QA-25, re-cut for the page cache: each mode's validator comes from the
        thing that actually decided the bytes being served.

        The per-page routes used to build the Markdown on the spot, so the record's
        own ``write_date`` was an honest answer.  They now serve ``llm_page_cache``
        (and warm it when it is empty), which makes the website's rebuild stamp the
        truthful one -- and it is not merely prettier: an editor save in the Website
        ``<editor>`` writes the arch on ``ir.ui.view``, not on ``website.page`` (that
        is why ``models/ir_ui_view.py`` exists), so a page body can be newer than its
        own ``write_date``.  A cached route advertising the older of the two would
        answer ``If-Modified-Since`` with a 304 and hand back stale Markdown.

        Two branches, because there are two modes to be right about: a cached
        website is as fresh as its last rebuild, a real-time one re-generates on
        every request and therefore has no rebuild stamp to point at, so it falls
        back to the record.

        Hardened with the ORM fact the first draft learned the hard way:
        ``write_date`` comes from ``cr.now()`` (``odoo17/odoo/models.py:4540``, set
        inside ``_write()``, which starts at ``:4522``) and PostgreSQL fixes the
        transaction timestamp at the first statement, so every ORM write inside one
        ``TransactionCase`` gets the *same* ``write_date``.  The record stamp is
        therefore moved with a SQL UPDATE, which is what a second crawler request
        sees in production after a write committed in an earlier transaction.
        """
        stamp_pushed_back = fields.Datetime.now() - timedelta(hours=2)
        self.env.cr.execute(
            "UPDATE website_page SET write_date = %s WHERE id = %s",
            (fields.Datetime.to_string(stamp_pushed_back), self.page.id))
        self.env.invalidate_all()

        cached = self.url_open(self.item_path)
        self.assertEqual(cached.status_code, 200)
        self.env.invalidate_all()
        rebuild = self.website.llm_cache_last_updated
        self.assertTrue(
            rebuild, 'the per-page route did not warm the cache it reads from')
        self.assertEqual(
            cached.headers['Last-Modified'], _http_utc(rebuild),
            'the header is not the rebuild stamp of the cached document (QA-25)')
        self.assertNotEqual(
            cached.headers['Last-Modified'], _http_utc(self.page.write_date),
            'a cached page still promised the older of the two dates (QA-25)')

        self.page.name = 'Contract Test Page Renamed'
        self.env.invalidate_all()
        renamed = self.url_open(self.item_path)
        self.assertNotEqual(cached.headers['ETag'], renamed.headers['ETag'],
                            'the validator did not follow the body (QA-25)')

        # Real-time re-generates every request, so nothing is cached to be fresher
        # than the record -- which is exactly where the old assertion still holds.
        self._set_ttl('realtime')
        dynamic = self.url_open(self.item_path)
        self.assertEqual(dynamic.status_code, 200)
        self.env.invalidate_all()
        self.assertFalse(
            self.website.llm_cache_last_updated,
            'real-time mode wrote a cache it promises not to use')
        self.assertEqual(
            dynamic.headers['Last-Modified'], _http_utc(self.page.write_date),
            'an uncached document is not validated by its own record stamp (QA-25)')

    # -- QA-25: conditional GET -----------------------------------------

    def test_conditional_get_with_if_none_match_returns_304(self):
        first = self.url_open('/llms.txt')
        etag = first.headers['ETag']
        r = self.url_open('/llms.txt', headers={'If-None-Match': etag})
        self.assertEqual(r.status_code, 304, 'a matching ETag must answer 304 (QA-25)')
        self.assertEqual(r.text, '', 'a 304 must not carry a body')
        self.assertEqual(r.headers.get('ETag'), etag)

    def test_conditional_get_with_if_modified_since_returns_304(self):
        first = self.url_open('/llms.txt')
        r = self.url_open('/llms.txt', headers={'If-Modified-Since': first.headers['Last-Modified']})
        self.assertEqual(r.status_code, 304, 'a date equal to Last-Modified must answer 304')
        self.assertEqual(r.text, '')

    def test_item_route_conditional_get_returns_304(self):
        first = self.url_open(self.item_path)
        r = self.url_open(self.item_path, headers={'If-None-Match': first.headers['ETag']})
        self.assertEqual(r.status_code, 304, 'the item route must honour If-None-Match too')
        self.assertEqual(r.text, '')

    def test_stale_etag_gets_the_full_body(self):
        """A validator must never answer 304 for content the client does not have."""
        self.url_open('/llms.txt')
        r = self.url_open('/llms.txt', headers={'If-None-Match': '"deadbeef"'})
        self.assertEqual(r.status_code, 200)
        self.assertIn('Contract Test Company', r.text)

    def test_etag_follows_the_body(self):
        """Same document -> same ETag; changed document -> different ETag."""
        before = self.url_open('/llms.txt').headers['ETag']
        again = self.url_open('/llms.txt').headers['ETag']
        self.assertEqual(before, again, 'the same document produced two ETags')
        self.website.llm_site_title = 'Contract Test Company Renamed'
        after = self.url_open('/llms.txt').headers['ETag']
        self.assertNotEqual(before, after, 'the ETag survived a content change')

    def test_etag_is_the_body_digest_not_a_timestamp(self):
        """A digest means the 304 logic has no clock to disagree with: two
        requests whose cache timestamp differs must still agree on the ETag."""
        body = self.url_open('/llms.txt').text
        r = self.url_open('/llms.txt')
        self.website.sudo().write({'llm_cache_last_updated': fields.Datetime.now() + timedelta(minutes=5)})
        later = self.url_open('/llms.txt').headers['ETag']
        self.assertEqual(r.headers['ETag'], '"%s"' % hashlib.sha1(body.encode('utf-8')).hexdigest())
        self.assertEqual(r.headers['ETag'], later, 'ETag moved with a timestamp, not the body')

    def test_vary_names_everything_the_document_depends_on(self):
        """QA-24, tightened while implementing QA-25.

        W3 shipped ``Vary: Accept-Language`` because that is what a language-
        negotiated document usually varies on -- but on this branch the frontend
        language is *not* taken from Accept-Language at all: http_routing picks the
        URL prefix, then the ``frontend_lang`` cookie, then the context, then the
        website default (``odoo17/addons/http_routing/models/ir_http.py:399-402,
        443-448``), and neither ``http_routing``, ``website`` nor ``odoo/http.py``
        reads the Accept-Language header anywhere (``grep -i accept-language`` over
        those files returns nothing).  A cache told to vary on Accept-Language
        alone is therefore still free to answer the French crawler with the body it
        stored for the crawler before it, which is exactly the outage QA-24 was
        written to prevent.  The language travels in a cookie, so the cookie has
        to be named.
        """
        for path in self._paths():
            r = self.url_open(path)
            self.assertEqual(r.status_code, 200, path)
            vary = r.headers.get('Vary', '')
            self.assertIn('Accept-Language', vary, '%s lost the QA-24 header' % path)
            self.assertIn('Cookie', vary,
                          '%s does not vary on the header the language actually '
                          'travels in (QA-24)' % path)

    # -- QA-36: a stateless document must not mint a session -------------

    def test_anonymous_crawler_gets_no_session_cookie(self):
        """QA-36: every crawler hit planted a 7-day ``session_id`` cookie -- and a
        row in the session store -- on a document that needs no state.

        The investigation, because the brief asked for one before any change:
        the cookie is *not* written by this module.  It is ``odoo.http``'s own
        ``Request._save_session()`` (``odoo17/odoo/http.py:1891-1905``), which sets
        the cookie whenever the request's ``session_id`` differs from the session's
        -- true for every anonymous first visit, at ``max-age`` = the configured
        session inactivity (7 days).  Proof it is platform-wide: the QA baseline
        ``qa_evidence/out/s12g6_warm_headers.log:29`` shows it on every route in
        that baseline, with a different sid per request.

        Odoo does give a route a documented way out: the routing dict is copied
        onto the request's session as ``can_save``
        (``self.request.session.can_save = routing.get('save_session', True)``,
        ``odoo17/odoo/http.py:2052``) and ``_save_session`` returns without
        minting anything when it is false.  These five routes are genuinely
        stateless: the website comes from the request host
        (``odoo17/addons/website/models/website.py:1125-1141``, cached by
        ``_get_current_website_id`` at ``:1143-1144``) and the language from the
        ``frontend_lang`` cookie
        (``odoo17/addons/http_routing/models/ir_http.py:444``), neither of which
        requires a saved session.  So this half of QA-36 is a module fix.

        The *other* half is not: the ``frontend_lang`` cookie is set by core's
        ``_frontend_pre_dispatch()``
        (``odoo17/addons/http_routing/models/ir_http.py:584-587``) on every
        frontend response whose language differs from the cookie, and a module
        cannot avoid it without overriding core dispatch.  Recorded as WON'T FIX
        in QA_REPORT.
        """
        for path in self._paths():
            r = self.url_open(path)
            self.assertEqual(r.status_code, 200, path)
            self.assertNotIn(
                'session_id', r.headers.get('Set-Cookie', ''),
                '%s minted a session cookie for an anonymous crawler (QA-36)' % path)
            self.assertNotIn(
                'session_id', r.cookies,
                '%s stored a session cookie in the client jar (QA-36)' % path)

    # -- QA-37: /llms.md is an alias, by design --------------------------

    def test_llms_md_is_an_intentional_alias_of_llms_txt(self):
        """QA-37 ACCEPTED BY DESIGN: keep the second URL, but make it a true alias --
        identical body, identical Cache-Control, only the Content-Type differs."""
        txt = self.url_open('/llms.txt')
        md = self.url_open('/llms.md')
        self.assertEqual(txt.status_code, 200)
        self.assertEqual(md.status_code, 200)
        self.assertEqual(txt.text, md.text, '/llms.md is no longer an alias of /llms.txt')
        self.assertEqual(txt.headers['Cache-Control'], md.headers['Cache-Control'])
        self.assertEqual(txt.headers['ETag'], md.headers['ETag'])
        self.assertEqual(md.headers.get('Content-Type'), 'text/markdown; charset=utf-8')
        self.assertEqual(txt.headers.get('Content-Type'), 'text/plain; charset=utf-8')


@tagged('post_install', '-at_install')
class TestLlmsCronContract(TransactionCase):
    """QA-16 / QA-33: one hourly cron that decides per website."""

    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        cls.website = cls.env['website'].search([], order='id', limit=1)
        cls.website.write({
            'llm_enabled': True,
            'llm_site_title': 'Cron Test Company',
            'llm_cache_ttl': 'hourly',
        })
        cls.Website = cls.env['website']

    def setUp(self):
        super().setUp()
        self.website._invalidate_llms_cache()

    def _crons(self):
        """Every llms cron installed in this database, base and companions."""
        return self.env['ir.cron'].sudo().search([
            ('model_id.model', '=', 'website'),
            ('code', 'like', '_cron_rebuild_llms_cache'),
        ])

    def _count_rebuilds(self, call):
        """Run ``call`` and return how many times a website was actually rebuilt.

        Counting the rebuilds (instead of just looking at the timestamp) is what
        makes QA-33 testable: three crons in one hour must still cost one build.
        """
        calls = []
        original = type(self.Website).action_rebuild_llms_cache

        def counting(self_website, *a, **kw):
            calls.append(1)
            return original(self_website, *a, **kw)

        type(self.Website).action_rebuild_llms_cache = counting
        try:
            call()
        finally:
            type(self.Website).action_rebuild_llms_cache = original
        return len(calls)

    # -- the shipped interval -------------------------------------------

    def test_cron_interval_is_one_hour(self):
        crons = self._crons()
        self.assertTrue(crons, 'no llms rebuild cron is installed')
        for cron in crons:
            self.assertEqual(
                (cron.interval_number, cron.interval_type), (1, 'hours'),
                '%s must run hourly so the "Cached (Hourly)" label and the cron '
                'agree (QA-16)' % cron.name)

    # -- per-mode behaviour ---------------------------------------------

    def test_realtime_mode_cron_never_writes_cache(self):
        """FINDINGS D-F: the cron cached documents for websites that asked for
        real-time generation, contradicting "builds on demand"."""
        self.website.llm_cache_ttl = 'realtime'
        self.Website._cron_rebuild_llms_cache()
        self.assertFalse(self.website.llm_cache_last_updated,
                         'the cron cached a realtime website')
        self.assertFalse(self.website.llm_txt_cache)

    def test_hourly_mode_cron_rebuilds_when_stale(self):
        self.website.llm_cache_ttl = 'hourly'
        self.website.sudo().write(
            {'llm_cache_last_updated': fields.Datetime.now() - timedelta(hours=2)})
        rebuilt = self._count_rebuilds(self.Website._cron_rebuild_llms_cache)
        self.assertEqual(rebuilt, 1, 'a two-hour-old cache must be rebuilt')
        self.assertGreater(self.website.llm_cache_last_updated,
                           fields.Datetime.now() - timedelta(minutes=5))

    def test_hourly_mode_cron_skips_fresh_cache(self):
        """Also the QA-33 mechanism: the 2nd and 3rd cron of the hour see a fresh
        cache and do nothing."""
        self.website.llm_cache_ttl = 'hourly'
        rebuilt = self._count_rebuilds(self.Website._cron_rebuild_llms_cache)
        self.assertEqual(rebuilt, 1)
        skipped = self._count_rebuilds(self.Website._cron_rebuild_llms_cache)
        self.assertEqual(skipped, 0, 'a cache built minutes ago was rebuilt again')

    def test_daily_mode_cron_skips_fresh_cache(self):
        self.website.llm_cache_ttl = 'daily'
        self.Website._cron_rebuild_llms_cache()
        self.assertTrue(self.website.llm_cache_last_updated)
        rebuilt = self._count_rebuilds(self.Website._cron_rebuild_llms_cache)
        self.assertEqual(rebuilt, 0, 'a daily cache one hour old must not be rebuilt')

    def test_daily_mode_cron_rebuilds_when_stale(self):
        self.website.llm_cache_ttl = 'daily'
        self.website.sudo().write(
            {'llm_cache_last_updated': fields.Datetime.now() - timedelta(hours=25)})
        rebuilt = self._count_rebuilds(self.Website._cron_rebuild_llms_cache)
        self.assertEqual(rebuilt, 1, 'a 25-hour-old daily cache must be rebuilt')

    def test_disabled_website_is_not_rebuilt(self):
        self.website.llm_enabled = False
        rebuilt = self._count_rebuilds(self.Website._cron_rebuild_llms_cache)
        self.assertEqual(rebuilt, 0)
        self.website.llm_enabled = True

    def test_all_installed_llms_crons_cost_one_rebuild(self):
        """QA-33: on a combined install three crons call the same model method.

        They stay installed -- a companion cannot know the base module exists
        (rule 4) -- and the per-website freshness check is what makes the extra
        crons cost nothing.

        The crons are *not* fired with ``method_direct_trigger()``.  On this branch
        that path grabs a NOWAIT row lock on the cron, runs its server action and
        stamps ``lastcall`` in the caller's cursor
        (``odoo17/odoo/addons/base/models/ir_cron.py:102-111``), i.e. it wraps the
        model method under test in bookkeeping that can itself fail on a row the
        enclosing transaction already touched -- and on the series where the job
        gets its own cursor it blocks on the locks this test holds, which is how an
        earlier draft hung the whole suite.  So each cron's code is checked
        to be the one model call, and that call is then made once per cron in this
        cursor, which is what the scheduler would have run.
        """
        self.website.llm_cache_ttl = 'hourly'
        self.website.sudo().write(
            {'llm_cache_last_updated': fields.Datetime.now() - timedelta(hours=2)})
        crons = self._crons()
        self.assertTrue(crons, 'no llms cron to trigger')
        for cron in crons:
            self.assertEqual(
                cron.code.strip(), 'model._cron_rebuild_llms_cache()',
                '%s does not call the method this test simulates' % cron.name)

        def run_all():
            for _ in crons:
                self.Website._cron_rebuild_llms_cache()

        rebuilt = self._count_rebuilds(run_all)
        self.assertEqual(
            rebuilt, 1,
            '%d llms crons triggered %d rebuilds of one website (QA-33)' % (len(crons), rebuilt))


@tagged('post_install', '-at_install')
class TestLlmsRouteRules(TransactionCase):
    """QA-32: the three modules must not disagree at the routing layer."""

    def _rules_for(self, path):
        """Every registry rule bound to ``path``, with its routing attributes."""
        mods = sorted(self.env.registry._init_modules | set(config['server_wide_modules']))
        converters = self.env['ir.http']._get_converters()
        found = []
        for url, endpoint in odoo_http._generate_routing_rules(mods, False, converters):
            if url == path:
                found.append(endpoint)
        return found

    def test_one_route_rule_per_index_path(self):
        """One *behaviour* per index path.

        Three addons each ship their own copy of the three index routes so that
        every one of them is installable alone (rule 4), so the registry does hold
        one rule per installed module.  The defect QA-32 describes was that those
        rules disagreed -- ``readonly=True`` on one, ``multilang`` unset on another
        -- which made the effective contract depend on which module registered
        first.  This test pins the agreement, and the documented attributes:
        ``multilang=False`` (the language comes from Accept-Language per QA-11, a
        ``/fr/llms.txt`` prefix would be yet another duplicate URL), and
        ``readonly`` false on the index routes because they fill the cache.
        """
        for path in INDEX_PATHS:
            endpoints = self._rules_for(path)
            self.assertTrue(endpoints, '%s is not routed' % path)
            shapes = {
                (e.routing.get('multilang'), e.routing.get('readonly'),
                 e.routing.get('auth'), e.routing.get('type'),
                 e.routing.get('website'), e.routing.get('sitemap'))
                for e in endpoints
            }
            self.assertEqual(
                len(shapes), 1,
                '%s is routed %d times with %d different attribute sets: %r (QA-32)'
                % (path, len(endpoints), len(shapes), shapes))
            multilang, readonly, auth, rtype, website, sitemap = shapes.pop()
            self.assertFalse(multilang, '%s must be multilang=False' % path)
            self.assertFalse(readonly, '%s writes the cache, so it must not be readonly' % path)
            self.assertEqual(auth, 'public')
            self.assertEqual(rtype, 'http')
            self.assertTrue(website)
            self.assertTrue(sitemap is False, '%s must stay out of the sitemap' % path)

    def test_item_routes_are_single_language_and_not_read_only(self):
        """Both per-page routes fill the page cache, so neither may run on a
        read-only cursor -- and both must refuse the ``/fr/`` language prefix.

        The pair used to be ``readonly=True`` because each request re-generated the
        Markdown on the spot.  They now serve ``llm_page_cache`` and warm it when it
        is empty (``get_llm_page_content``), which is a *write*: on a read-only
        transaction PostgreSQL aborts with ``cannot execute UPDATE in a read-only
        transaction``, so the first crawler hit after an invalidation would have
        turned into a 500.  Pinning the flag here is what keeps a future "it's only
        a GET, put readonly back" change from being a production outage.

        ``multilang=False`` stays asserted for the same reason as the index routes:
        the language is negotiated per request (QA-11), so a URL prefix would be a
        third copy of one document.  The mirrored route is checked as a rule
        *pattern* rather than as ``/contract-test-page.md`` because the attributes
        belong to the definition, and this class has no page-per-website fixture to
        build URLs from.
        """
        for pattern in ITEM_RULES:
            endpoints = self._rules_for(pattern)
            self.assertTrue(endpoints, '%s is not registered' % pattern)
            shapes = {
                (e.routing.get('multilang'), e.routing.get('readonly'),
                 e.routing.get('auth'), e.routing.get('type'),
                 e.routing.get('website'), e.routing.get('sitemap'))
                for e in endpoints
            }
            self.assertEqual(
                len(shapes), 1,
                '%s is routed %d times with %d different attribute sets: %r (QA-32)'
                % (pattern, len(endpoints), len(shapes), shapes))
            multilang, readonly, auth, rtype, website, sitemap = shapes.pop()
            self.assertFalse(multilang, '%s must be multilang=False' % pattern)
            self.assertFalse(
                readonly,
                '%s warms llm_page_cache, so a read-only cursor cannot serve it'
                % pattern)
            self.assertEqual(auth, 'public', '%s must be reachable by a crawler' % pattern)
            self.assertEqual(rtype, 'http')
            self.assertTrue(website)
            self.assertTrue(sitemap is False, '%s must stay out of the sitemap' % pattern)

    def test_llms_routes_opt_out_of_the_session_cookie(self):
        """QA-36 at the routing layer: the key that keeps a crawler hit stateless.

        Asserted here as well as on the live response because the behaviour comes
        from this dict -- ``Dispatcher.pre_dispatch()`` reads ``save_session`` out
        of it (``odoo17/odoo/http.py:2044,2052``) and nothing else can turn the
        cookie off.
        """
        for path in INDEX_PATHS + ITEM_RULES:
            endpoints = self._rules_for(path)
            self.assertTrue(endpoints, '%s is not routed' % path)
            for endpoint in endpoints:
                self.assertIs(
                    endpoint.routing.get('save_session'), False,
                    '%s must be declared save_session=False, routing is %r (QA-36)'
                    % (path, dict(endpoint.routing)))
